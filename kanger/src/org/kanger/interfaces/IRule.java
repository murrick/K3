package org.kanger.interfaces;

import java.util.Set;

/**
 * Публичное представление самостоятельного логического объекта KANGER.
 *
 * <p>Rule может быть составным правилом либо утверждением, содержащим один
 * предикат с аргументами. Его идентификатор выражает identity логического
 * объекта и используется для ссылок между структурами KANGER; он не является
 * физическим адресом в storage и не выводится только из исходного текста.
 * Канонизация, повторное введение основания и восстановление выполняются
 * фабрикой правил и текущим транзакционным контекстом.</p>
 *
 * <p>Интерфейс различает неизменяемое происхождение правила и его актуальную
 * материализацию. {@link #getOrigin()} возвращает исходное представление,
 * тогда как {@link #toString(IMind)} строит представление в видимом состоянии
 * конкретного Mind, включая лениво загруженные ссылки и текущий overlay.</p>
 *
 * <p>Статусы generated, query, deleted и restored описывают разные стороны
 * lifecycle объекта: происхождение в выводе, принадлежность операции запроса
 * и транзакционную видимость. Они не образуют взаимоисключающую enum-модель и
 * должны интерпретироваться совместно.</p>
 *
 * <p>Для утверждений доступны {@link #getPredicate()} и
 * {@link #getArguments()}. Вызов этих методов для составного правила является
 * ошибкой контракта вызывающей стороны. Связи {@link #getCauses()} выражают
 * непосредственное provenance утверждения и позволяют строить граф объяснения
 * результата вывода.</p>
 */
public interface IRule {

    /**
     * Возвращает identity правила в пространстве логических объектов KANGER.
     *
     * <p>Идентификатор сохраняется при транзакционном переносе того же объекта,
     * но не является storage-offset, номером строки или хешем исходного текста.</p>
     *
     * @return идентификатор правила.
     */
    long getId();

    /**
     * Возвращает исходное текстовое представление правила.
     *
     * <p>Происхождение не заменяется актуальной материализацией и сохраняет
     * форму, связанную с моментом создания или компиляции объекта.</p>
     *
     * @return исходное представление правила.
     * @throws Exception если исходное представление нельзя получить из
     *                   доступного состояния или storage.
     */
    String getOrigin() throws Exception;

    /**
     * Строит актуальное текстовое представление правила в указанном Mind.
     *
     * <p>Для утверждения представление разрешает дерево правила, параметры,
     * ленивые ссылки и транзакционно видимые значения. Метод предназначен для
     * диагностики и отображения; его результат не является canonical identity
     * или гарантированным persistence-форматом.</p>
     *
     * @param mind транзакционный контекст разрешения ссылок и overlay.
     * @return актуальное текстовое представление правила.
     */
    String toString(IMind mind);

    /**
     * Указывает, что правило было создано как производное в процессе вывода.
     *
     * <p>Generated-статус описывает происхождение объекта и сам по себе не
     * определяет его текущую видимость, удаление или последующее повышение в
     * самостоятельное основание.</p>
     *
     * @return {@code true}, если правило имеет производное происхождение.
     */
    boolean isGenerated();

    /**
     * Указывает принадлежность правила к операции запроса.
     *
     * <p>Статус охватывает как инициирующее правило запроса, так и связанные с
     * ним служебные объекты. Он не означает автоматически истинность результата
     * и не заменяет анализ насыщенного состояния Mind.</p>
     *
     * @return {@code true}, если правило относится к запросу.
     */
    boolean isQuery();

    /**
     * Проверяет, скрыто ли правило удалением в указанном транзакционном
     * контексте.
     *
     * <p>Удаление является частью overlay и не обязано означать немедленное
     * физическое уничтожение persistent-представления.</p>
     *
     * @param mind контекст, относительно которого проверяется видимость.
     * @return {@code true}, если правило помечено для удаления.
     */
    boolean isDeleted(IMind mind);

    /**
     * Проверяет, восстановлено ли правило в указанном транзакционном контексте.
     *
     * <p>Restored означает, что объект, скрытый удалением на нижнем видимом
     * уровне, вновь введён или произведён в текущем overlay. Восстановление
     * изменяет видимость основания, а не создаёт новую текстовую identity само
     * по себе.</p>
     *
     * @param mind контекст проверки восстановления.
     * @return {@code true}, если правило восстановлено на этом уровне.
     */
    boolean isRestored(IMind mind);

    /**
     * Указывает наличие t-переменных, допускающих подстановку при выводе.
     *
     * @return {@code true}, если правило содержит substitutable-позиции.
     */
    boolean isSubstitutable();

    /**
     * Указывает наличие u-переменных — внутренних свидетелей KANGER.
     *
     * <p>Такие переменные принадлежат логическому и транзакционному контексту
     * правила и не обязаны появляться во внешней проекции значений.</p>
     *
     * @return {@code true}, если правило содержит u-переменные.
     */
    boolean isAbstractive();

    /**
     * Указывает, является ли Rule утверждением с одним предикатом.
     *
     * <p>Историческое имя {@code isStored()} не означает, что объект физически
     * записан в persistent storage. Метод различает assertion surface и
     * составное правило; только для утверждения допустимы
     * {@link #getPredicate()} и {@link #getArguments()}.</p>
     *
     * @return {@code true}, если Rule представляет утверждение.
     */
    boolean isStored();

    /**
     * Возвращает сторону логической секвенции, к которой относится правило.
     *
     * @return {@code true} для антецедента, {@code false} для сукцедента.
     * @throws Exception если принадлежность нельзя разрешить из доступного
     *                   представления правила.
     */
    boolean isAntc() throws Exception;

    /**
     * Возвращает каноническое определение предиката утверждения.
     *
     * @return предикат данного утверждения.
     * @throws Exception если Rule является составным правилом или предикат
     *                   нельзя разрешить.
     */
    IPredicate getPredicate() throws Exception;

    /**
     * Возвращает упорядоченный список аргументов утверждения.
     *
     * <p>Значения отдельных аргументов могут зависеть от Mind и вычисляться
     * через соответствующие интерфейсы аргументов; сам список описывает
     * структуру assertion.</p>
     *
     * @return список аргументов утверждения.
     * @throws Exception если Rule является составным правилом или аргументы
     *                   нельзя разрешить.
     */
    IList getArguments() throws Exception;

    /**
     * Возвращает непосредственные основания появления данного утверждения.
     *
     * <p>Связи cause образуют provenance-граф знания. Они предназначены для
     * объяснения результата, диагностики и truth-maintenance; множество не
     * обязано содержать транзитивное замыкание всех предков.</p>
     *
     * @return непосредственные узлы-основания; для корневого основания
     *         множество может быть пустым.
     */
    Set<ICause> getCauses();

    /**
     * Возвращает пользовательский комментарий, связанный с правилом.
     *
     * <p>Комментарий является метаданными: он не участвует в canonical identity,
     * сопоставлении, насыщении или истинностной семантике. Возвращаемый текст
     * сохраняет синтаксические маркеры {@code //} либо блокового комментария.</p>
     *
     * @return текст комментария либо значение, принятое реализацией для его
     *         отсутствия.
     * @throws Exception если метаданные нельзя получить из доступного storage.
     */
    String getComment() throws Exception;

    /**
     * Устанавливает пользовательский комментарий правила.
     *
     * <p>Операция изменяет только comment metadata и не должна менять identity,
     * аргументы, provenance или результат логического вывода. Вызывающая сторона
     * обязана передать текст в поддерживаемой форме с маркерами {@code //} либо
     * блокового комментария.</p>
     *
     * @param comment новый текст комментария.
     * @throws Exception если формат недопустим либо изменение невозможно в
     *                   текущем lifecycle/storage-контексте.
     */
    void setComment(String comment) throws Exception;
}
